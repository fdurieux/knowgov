"""Vendor the CargoQuote subject and the proof-of-concept record from a pumllint checkout.

    python tools/vendor_subject.py ../pumllint                   # at the tag the checkout is on
    python tools/vendor_subject.py ../pumllint --allow-untagged  # a commit that carries no tag
    python tools/vendor_subject.py ../pumllint --dry-run         # say what would change, write nothing

The subject (the kit, the CargoQuote documents, the acceptance oracle) and the record of the
proof of concept (``kg_experiment/results``, the pre-registration) were made in pumllint and
stay there (decision-0001). This tool copies a fixed path set byte for byte into
``subjects/cargo_quote/``, keeping pumllint's relative layout so the oracle's own path logic
and the record's ``SHA256SUMS`` paths stay valid, and writes ``SOURCE.md`` from git's own
answers: the tag or commit, its subject and date, the sha256 of every file, the earlier copies
carried forward. The checkout must be clean; an untagged commit needs ``--allow-untagged`` and
the note says so. Nothing is fetched. ``tests/test_vendor_subject.py`` holds every file to its
digest.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "subjects" / "cargo_quote"
PATHS = ("kg_experiment/kit", "kg_experiment/results", "kg_experiment/PREREGISTRATION.md",
         "stack_experiment/cargo_quote", "stack_experiment/smoke_test.py",
         "tools/acceptance/__init__.py", "tools/acceptance/cargo_quote_suite.py",
         "tools/acceptance/runner_child.py", "tools/acceptance/suites.py")
WHAT = ("the kit (`kg_experiment/kit`), the CargoQuote documents and reference implementation "
        "(`stack_experiment/cargo_quote`), the acceptance oracle (`stack_experiment/smoke_test.py`, "
        "`tools/acceptance`), the record (`kg_experiment/results`) and the pre-registration; nothing else")
MARK = "generated by `tools/vendor_subject.py`"


def _git(checkout: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(checkout), *args], check=True, capture_output=True, text=True,
                          encoding="utf-8").stdout.strip()


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def describe(checkout: Path, allow_untagged: bool) -> dict:
    """What git says about the checkout: refuses a dirty tree and, unless allowed, an untagged HEAD."""
    if not (checkout / ".git").exists():
        raise SystemExit(f"{checkout} is not a git checkout")
    if _git(checkout, "status", "--porcelain", "--untracked-files=no"):
        raise SystemExit(f"{checkout} has uncommitted changes; the copy must come from a commit")
    commit = _git(checkout, "rev-parse", "HEAD")
    subject, date = _git(checkout, "log", "-1", "--format=%s%n%cs").split("\n", 1)
    try:
        tag = _git(checkout, "describe", "--tags", "--exact-match", "HEAD")
    except subprocess.CalledProcessError:
        if not allow_untagged:
            raise SystemExit(f"{commit[:7]} carries no tag; the subject is read at a tag (pass --allow-untagged to copy a commit)")
        tag = ""
    try:
        url = _git(checkout, "remote", "get-url", "origin")
    except subprocess.CalledProcessError:
        url = ""
    m = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?$", url)
    repo = m.group(1) if m else ""
    files = sorted(f for f in _git(checkout, "ls-files", "-z", "--", *PATHS).split("\0") if f)
    missing = [p for p in PATHS if not (checkout / p).exists()]
    if missing:
        raise SystemExit(f"the checkout lacks {', '.join(missing)}")
    return {"commit": commit, "subject": subject, "date": date, "tag": tag, "repo": repo, "files": files}


def earlier_copies(note: str) -> list[tuple[str, str, str]]:
    rows = re.findall(r"^\| `([^`|]*)` \| `([0-9a-f]{7,40})` \| (\d{4}-\d{2}-\d{2}) \|$", note, re.M)
    return [(t, c[:7], d) for t, c, d in rows]


def current_copy(note: str) -> tuple[str, str, str]:
    tag = re.search(r"^\| tag \| `(v[0-9][^`]*)`", note, re.M)
    commit = re.search(r"\| commit \| `([0-9a-f]{40})`", note)
    copied = re.search(r"^\| copied \| (\d{4}-\d{2}-\d{2})", note, re.M)
    return (tag.group(1) if tag else "", commit.group(1)[:7] if commit else "", copied.group(1) if copied else "")


def source_note(info: dict, digests: dict[str, str], copied: str, earlier: list[tuple[str, str, str]]) -> str:
    tag_cell = (f"`{info['tag']}` — the platform reads the tag; the commit is what it resolves to" if info["tag"]
                else "none — an untagged commit, copied with `--allow-untagged`; re-vendor at the next pumllint tag that carries it")
    lines = [
        "# Vendored copy of the CargoQuote subject and the proof-of-concept record, from pumllint", "",
        "| | |", "|---|---|",
        f"| source repository | `{info['repo'] or 'fdurieux/pumllint'}` (the experiment's home; synthetic content, no bank data) |",
        f"| commit | `{info['commit']}` — \"{info['subject']}\", {info['date']} |",
        f"| tag | {tag_cell} |",
        f"| what is copied | {WHAT} |",
        f"| files | {len(digests)} |",
        f"| copied | {copied}, byte for byte, {MARK} from a clean checkout at that commit |",
        "",
        "pumllint's relative layout is kept under this directory so the oracle's own path",
        "logic and the record's `SHA256SUMS` paths stay valid. The record under",
        "`kg_experiment/results` is pumllint's and is never written here: the platform's",
        "re-runs land under `runs/`. The documents are the subject the harness loads and",
        "the arms read; the oracle grades what the arms wrote. This table is the record of",
        "which bytes the platform carries. To refresh it, check pumllint out at the tag you",
        "want and run `python tools/vendor_subject.py <checkout>`, which rewrites this file;",
        "`tests/test_vendor_subject.py` holds every file to its digest.",
        "",
        "| file | sha256 |", "|---|---|",
    ]
    lines += [f"| `{rel}` | `{sha}` |" for rel, sha in sorted(digests.items())]
    if earlier:
        lines += ["", "## Earlier copies", "", "| tag | commit | copied |", "|---|---|---|"]
        lines += [f"| `{t}` | `{c}` | {d} |" for t, c, d in earlier]
    return "\n".join(lines) + "\n"


def vendor(checkout: Path, dest: Path = DEST, *, allow_untagged: bool = False, copied: str | None = None,
           dry_run: bool = False, out=print) -> dict:
    info = describe(checkout, allow_untagged)
    new = {rel: _sha(checkout / rel) for rel in info["files"]}
    old_note = (dest / "SOURCE.md").read_text(encoding="utf-8") if (dest / "SOURCE.md").exists() else ""
    old = {p.relative_to(dest).as_posix(): _sha(p) for p in dest.rglob("*")
           if p.is_file() and p.name != "SOURCE.md" and "__pycache__" not in p.parts} if dest.exists() else {}
    added = sorted(set(new) - set(old))
    removed = sorted(set(old) - set(new))
    changed = sorted(k for k in set(new) & set(old) if new[k] != old[k])
    copied = copied or dt.date.today().isoformat()
    earlier = earlier_copies(old_note)
    cur = current_copy(old_note)
    if cur[1] and cur[1] != info["commit"][:7] and cur[1] not in {c for _, c, _ in earlier}:
        earlier.insert(0, cur)
    note = source_note(info, new, copied, earlier)
    out(f"{info['repo'] or checkout} at {info['tag'] or 'no tag'} ({info['commit'][:7]}, {info['date']}): "
        f"{len(new)} files; {len(added)} added, {len(removed)} removed, {len(changed)} changed")
    for label, items in (("added", added), ("removed", removed), ("changed", changed)):
        for rel in items:
            out(f"  {label}: {rel}")
    if not dry_run:
        for rel in old:
            (dest / rel).unlink()
        for d in sorted((p for p in dest.rglob("*") if p.is_dir()), reverse=True) if dest.exists() else []:
            if not any(d.iterdir()):
                d.rmdir()
        for rel in new:
            (dest / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(checkout / rel, dest / rel)
        (dest / "SOURCE.md").write_text(note, encoding="utf-8", newline="\n")
        out(f"wrote {dest / 'SOURCE.md'}")
    return {**info, "digests": new, "added": added, "removed": removed, "changed": changed, "note": note}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("checkout", type=Path, help="a clean checkout of fdurieux/pumllint at the tag to vendor")
    ap.add_argument("--dest", type=Path, default=DEST, help=f"where the copy lives (default {DEST.relative_to(ROOT).as_posix()})")
    ap.add_argument("--allow-untagged", action="store_true", help="copy a commit that carries no tag")
    ap.add_argument("--date", help="the 'copied' date to record (default today)")
    ap.add_argument("--dry-run", action="store_true", help="report what would change and write nothing")
    a = ap.parse_args(argv)
    vendor(a.checkout.resolve(), a.dest.resolve(), allow_untagged=a.allow_untagged, copied=a.date, dry_run=a.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
